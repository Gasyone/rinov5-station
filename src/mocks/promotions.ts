export function getPromotionBranches(promotions: PromotionItem[]): string[] {
  const branches = new Set<string>()
  promotions.forEach((p) => {
    if (p.branch) branches.add(p.branch)
  })
  return Array.from(branches)
}

export function getPromotionTypes(promotions: PromotionItem[]): PromotionType[] {
  const types = new Set<PromotionType>()
  promotions.forEach((p) => types.add(p.type))
  return Array.from(types)
}

export function getPromotionDiscountTypes(promotions: PromotionItem[]): PromotionDiscountType[] {
  const types = new Set<PromotionDiscountType>()
  promotions.forEach((p) => types.add(p.discountType))
  return Array.from(types)
}
