export interface PaymentRecord {
  id: string
  sequenceNo?: number
  amount: number
  paymentType?: string
  paymentMethod?: string
  bankAccount?: string
  paidAt?: string
  note?: string
  code?: string
  method?: string
  time?: string
  staff?: string
  reconciliationStatus?: 'reconciled' | 'unreconciled' | string
}

export interface OrderItem {
  productId: string
  productName: string
  quantity: number
  unitPrice: number
  subtotal: number
  discount?: number
  studentName?: string
  programName?: string
  teacherType?: string
  packageType?: string
  packageCategory?: 'combo' | 'tutor' | 'single_course' | 'book_service' | 'physical'
  categoryName?: string
  isRenewal?: boolean
  isCompleted?: boolean
  voucherCode?: string
  voucherDiscount?: number
  bonusText?: string
  fulfillmentType?: 'service' | 'physical'
  activationStatus?: 'activated' | 'pending_activation' | 'not_activated'
  sessionsGranted?: number
  sessionsTotal?: number
  handoverStatus?: 'handed_over' | 'pending_handover' | 'not_handed_over'
  handoverDate?: string
  activatedAt?: string
}

export interface OrderReceiptItem {
  id: string
  code: string
  amount: number
  method: string
  timestamp: string
  status: string
}

export interface Order {
  id: string
  orderNo: string
  studentId: string
  studentName: string
  items: OrderItem[]
  totalAmount: number
  discountAmount: number
  finalAmount: number
  paidAmount?: number
  paidCount?: number
  remainingAmount?: number
  paymentHistory?: PaymentRecord[]
  paymentMethod: "cash" | "bank_transfer" | "credit_card" | "momo"
  paymentStatus: "paid" | "unpaid" | "partial"
  status: "completed" | "processing" | "pending" | "cancelled" | "refunded"
  branch: string
  saleBy: string
  createdAt: string
  notes?: string
  customerName?: string
  customerPhone?: string
  recipientName?: string
  shippingAddress?: string
  paymentMethodTag?: string
  receiptNumber?: string
  receiptTime?: string
  receiptAmount?: number
  receiptMethod?: string
  receiptStatus?: string
  paymentOption?: string
  receipts?: OrderReceiptItem[]
  hasDepositStudyNow?: boolean
  hasDepositPre?: boolean
  canConvertProduct?: boolean
  remainingSessions?: number
  isExpired?: boolean
  updatedAt?: string
}

