export function getBookingTests(filters?: {
  search?: string
  school?: string
  subject?: BookingSubject
  status?: BookingStatus
}): BookingTest[] {
  return mockBookingTests.filter((booking) => {
    if (filters?.subject && booking.subject !== filters.subject) return false
    if (filters?.school && booking.school !== filters.school) return false
    if (filters?.status && booking.status !== filters.status) return false
    if (filters?.search) {
      const query = filters.search.toLowerCase()
      const haystack = [
        booking.childName,
        booking.familyName,
        booking.phone,
        booking.id,
        booking.school,
        booking.classroom,
      ].join(" ").toLowerCase()
      if (!haystack.includes(query)) return false
    }
    return true
  })
}

export function addBookingTest(newBooking: BookingTest): BookingTest {
  mockBookingTests.unshift(newBooking)
  return newBooking
}

